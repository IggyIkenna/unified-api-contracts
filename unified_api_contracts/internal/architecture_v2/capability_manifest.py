class CapabilityNode(BaseModel):
    """A single node in the capability graph."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    kind: CapabilityNodeKind = Field(description="Vocabulary category of this node (archetype, venue, chain, …).")
    node_id: str = Field(
        description=(
            "Stable, unique identifier for this node within its ``kind``. "
            "Should match the StrEnum value where one exists (e.g. "
            "``CARRY_STAKED_BASIS``, ``hyperliquid``). Never reassigned."
        )
    )
    label: str = Field(
        description=(
            "Human-readable display label used by the wizard UI. "
            "May differ from ``node_id`` for readability (e.g. "
            "``node_id='CARRY_STAKED_BASIS'`` → ``label='Carry: Staked Basis'``)."
        )
    )
    metadata: dict[str, str] = Field(
        default_factory=dict,
        description=(
            "Arbitrary key-value metadata attached to the node. "
            "Used for extra context surfaced in side-by-side help text. "
            "Keys must be valid Python identifiers; values are strings."
        ),
    )


class AgentAnnotation(BaseModel):
    """An agent-orchestrator answer written back into a capability edge.

    Once written, the edge's ``gap_type`` should be cleared (the gap is
    resolved) and the edge status updated accordingly. Annotations are
    append-only and keyed by ``annotated_at`` UTC datetime.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    annotated_by: str = Field(
        description=(
            "Agent or script identity that produced the annotation "
            "(e.g. ``'agent-orchestrator/slot-3'``, ``'generate_capability_manifest.py'``)."
        )
    )
    annotated_at: datetime = Field(
        description=(
            "UTC datetime when the annotation was written. "
            "Must be timezone-aware (``timezone.utc``). "
            "Credits are spent once — the manifest caches the answer."
        )
    )
    answer: str = Field(description="Free-text answer or reasoning produced by the agent.")
    resolved_status: CapabilityEdgeStatus = Field(
        description=(
            "The edge status the agent concluded after scanning. The manifest exporter uses this to update the edge."
        )
    )


class CapabilityEdge(BaseModel):
    """A directed, typed edge in the capability graph."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    from_node_id: str = Field(
        description=("``node_id`` of the source node. Must match an entry in ``CapabilityManifest.nodes``.")
    )
    to_node_id: str = Field(
        description=("``node_id`` of the target node. Must match an entry in ``CapabilityManifest.nodes``.")
    )
    relation: str = Field(
        description=(
            "Named relation describing the edge semantics. Free-text but "
            "should be drawn from a controlled vocabulary "
            "(e.g. ``'supports'``, ``'requires'``, ``'uses_algo'``, "
            "``'min_data_to_run'``, ``'emits_instruction'``). "
            "The wizard renders this as the edge label."
        )
    )
    status: CapabilityEdgeStatus = Field(
        description=(
            "Availability status of this capability edge. "
            "``not_registered`` is the honest baseline when a registry gap "
            "means the exporter cannot yet populate the edge."
        )
    )
    gap_type: CapabilityGapType | None = Field(
        default=None,
        description=(
            "Typed gap reason. Must be set when ``status`` is "
            "``not_registered`` or when the edge is known-broken. "
            "Cleared once an ``agent_annotation`` resolves the gap."
        ),
    )
    reason: str | None = Field(
        default=None,
        description=(
            "Human-readable explanation of the status, especially for "
            "``not_available`` (logical dead-end) and ``partial`` (caveats). "
            "The wizard renders this as the greyed-option tooltip."
        ),
    )
    readiness: str | None = Field(
        default=None,
        description=(
            "Operational maturity label: "
            "``'backtest-only'`` | ``'shadow-observed'`` | "
            "``'staging-proven'`` | ``'live-proven'``. "
            "Derived from the deployments registry + archived plans."
        ),
    )
    agent_annotation: AgentAnnotation | None = Field(
        default=None,
        description=(
            "Agent-orchestrator answer for a ``needs_code_scan`` gap. "
            "Written back by the agent once the scan completes. "
            "Credits are spent once — consumers read from here, never re-scan."
        ),
    )


