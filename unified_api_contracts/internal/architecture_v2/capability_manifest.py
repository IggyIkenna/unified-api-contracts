"""Capability manifest schema — the typed graph of what the system can do.

Every edge in the manifest carries a status (available/partial/not_available/
not_registered) and, where applicable, a typed gap reason and an optional
agent annotation written back by the agent-orchestrator so questions are
answered once and cached.

The manifest is generated by
``unified-trading-pm/scripts/openapi/generate_capability_manifest.py``.
This module owns only the schema; the generator populates it.

Codex SSOT:
  ``codex/09-strategy/architecture-v2/capability-wizard.md``
Plan:
  ``plans/active/capability_wizard_and_manifest_2026_06_11.md``
  Phase 1 [SPEC] P0.
"""

from __future__ import annotations

from datetime import datetime
from decimal import Decimal
from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field

# ---------------------------------------------------------------------------
# Node kinds
# ---------------------------------------------------------------------------


class CapabilityNodeKind(StrEnum):
    """Vocabulary of node types in the capability graph.

    Each value corresponds to a dimension of the wizard walkthrough (Stage A-J
    in ``capability-wizard-question-bank.md``).
    """

    ARCHETYPE = "archetype"
    """A ``StrategyArchetype`` entry (53 total)."""

    LEG = "leg"
    """A structural leg of a multi-leg archetype (``ArchetypeLegSpec``).

    Sourced from ``ARCHETYPE_LEG_STRUCTURES`` (F22 leg-truth SSOT). An
    ``archetype --has_leg--> leg`` edge carries the leg ``role`` + ``required``
    flag; ``leg --trades_instrument--> instrument_type`` and
    ``leg --supports--> venue`` edges give the per-leg restriction surface the
    flat ``(asset_group, instrument_type)`` cell model cannot express.
    """

    FAMILY = "family"
    """A ``StrategyFamily`` entry (9 total)."""

    VENUE = "venue"
    """A named trading venue / DEX / lending protocol."""

    CHAIN = "chain"
    """A blockchain network (Ethereum, Solana, Arbitrum, …)."""

    INSTRUMENT_TYPE = "instrument_type"
    """An ``ArchetypeInstrumentType`` value (spot/perp/dated_future/…)."""

    EXECUTION_ALGO = "execution_algo"
    """An execution algorithm (SOR, sor_twap, swap_twap, …)."""

    INSTRUCTION_TYPE = "instruction_type"
    """An ``InstructionActionV2`` value (TRADE/SWAP/LEND/…)."""

    FEATURE_GROUP = "feature_group"
    """A feature group from the features-service registry (~34 groups)."""

    ML_MODEL = "ml_model"
    """A registered ML model from ml-service model_registry."""

    DATA_SOURCE = "data_source"
    """A named data source / vendor (hyperliquid, databento, polymarket_clob, …)."""

    FUND_STRUCTURE = "fund_structure"
    """A fund-structure offering (pooled/SMA/prop)."""

    WALLET = "wallet"
    """A wallet type in the hierarchy (treasury/hot) per share class."""

    BROKER = "broker"
    """A TradFi broker usable for execution or custody."""

    CUSTODY_PROVIDER = "custody_provider"
    """A custody provider (Copper, CEFFU, CLOUD_KMS_ENCRYPTED, …).

    Historically abused as a catch-all (F49); the additive kinds below let the
    PM exporter (Wave B) re-kind the surfaces it was overloading onto this.
    """

    SIGNING_SURFACE = "signing_surface"
    """A real custody / transaction-signing surface (``SigningSurface`` enum —
    CLOUD_KMS_ENCRYPTED / COPPER_MPC / FIREBLOCKS_MPC / LOCAL_KEY / MOCK).

    Sourced from ``custody_surfaces.OFFERED_SIGNING_SURFACES`` (F49 re-kind):
    these are the HSM/MPC tiers a wallet signs through, NOT the higher-level
    ``custody_provider`` business relationship. May-23 ships CLOUD_KMS_ENCRYPTED;
    June-1 flips per-wallet to COPPER_MPC."""

    RISK_GATE_LAYER = "risk_gate_layer"
    """A risk-gate / pre-flight check layer in the execution pipeline."""

    KILL_SWITCH_REASON = "kill_switch_reason"
    """A kill-switch / circuit-breaker trigger reason."""

    GAP_REGISTRY = "gap_registry"
    """A capability gap registry (the forcing-function registries that surface
    unregistered cells)."""

    COLLATERAL_POLICY = "collateral_policy"
    """A per-venue collateral / margin / liquidation policy
    (``collateral_registry.CollateralPolicy``)."""


# ---------------------------------------------------------------------------
# Edge statuses + gap types
# ---------------------------------------------------------------------------


class CapabilityEdgeStatus(StrEnum):
    """Availability status of a capability edge.

    The wizard renders these as visual indicators:
    - ``available``      → green tick
    - ``partial``        → amber tick (supported but with caveats)
    - ``not_available``  → red cross (logical dead-end or known limitation)
    - ``not_registered`` → grey question mark (registry gap — schematically
      possible but no registry entry yet; the forcing-function state)
    """

    AVAILABLE = "available"
    PARTIAL = "partial"
    NOT_AVAILABLE = "not_available"
    NOT_REGISTERED = "not_registered"


class CapabilityGapType(StrEnum):
    """Typed reason why an edge carries a gap status.

    Used by the escalation pipeline:
    - ``missing_registry``   → gap in a UAC registry (fill the registry)
    - ``missing_extraction`` → registry may exist but the exporter cannot yet
      extract / derive the value
    - ``needs_code_scan``    → requires an agent-orchestrator code scan to
      determine definitively; answer is written back as ``agent_annotation``
    - ``logical_dead_end``   → structurally impossible (e.g. options on a
      sports venue); correct and expected, not a build gap
    """

    MISSING_REGISTRY = "missing_registry"
    MISSING_EXTRACTION = "missing_extraction"
    NEEDS_CODE_SCAN = "needs_code_scan"
    LOGICAL_DEAD_END = "logical_dead_end"


