"""Fund + business_unit + reserving_business_unit_id registry — G2.8.

Stage 3E § 2.8. Stage-3a § 3.2 flagged the missing typed registry mapping
each IM Pooled fund / Reg Umbrella fund / SMA / admin + IM-desk to its
canonical ``business_unit`` + ``reserving_business_unit_id`` + custody
model. Today allocator call-sites and reporting surfaces use free-form
strings; ``StrategyAvailabilityEntry.reserving_business_unit_id`` is a
free ``str | None`` with no registry validation.

This module ships the typed registry. Consumers:

* ``strategy-service/portfolio_allocator/service.py`` — look up the
  reserving business unit for a fund instead of concatenating strings.
* Reporting surfaces (per-fund breakdowns, commercial-path slicing).
* UI mirror at ``unified-trading-system-ui/lib/admin/fund-business-unit.ts``
  (generated by ``sync-fund-business-unit-to-ui.sh``, G1.8 pattern).

Custody model is load-bearing for the IM commercial split:

* **IM Pooled** funds are custodied by Copper (third-party custodian);
  Odum never touches the coins / cash. Subs / redemptions flow via the
  Odum portal but settle via Copper.
* **IM SMA** + **DART** clients retain custody on the venue in the
  client's own account; Odum holds execute+read scoped API keys.
* **Reg Umbrella** also uses client-owned-venue custody (the client
  operates their own stack under Odum's FCA permissions).

The POD affiliate referenced in the custody memo is **internal-only**;
registry rows for IM Pooled carry ``custody_model=COPPER_CUSTODIAN``
and must not surface POD anywhere in public UI strings.

SSOT:

* Plan: ``plans/active/refactor_g2_8_fund_business_unit_registry_2026_04_20.md``
* Custody memo:
  ``memory/project_custody_model_per_path_2026_04_20.md``
* Codex:
  ``codex/14-playbooks/shared-core/fund-administration-and-custody.md``
  ``codex/14-playbooks/cross-cutting/sma-vs-pooled.md``
"""

from __future__ import annotations

from collections.abc import Iterable
from enum import StrEnum
from typing import Final, Literal

from pydantic import BaseModel, ConfigDict


class CustodyModel(StrEnum):
    """Who holds the underlying assets."""

    CLIENT_OWNED_VENUE = "CLIENT_OWNED_VENUE"
    """Client retains custody on the venue in their own account.
    Odum holds scoped API keys (execute + read) — not read-only.
    Applies to IM SMA, DART, and Reg Umbrella paths."""

    COPPER_CUSTODIAN = "COPPER_CUSTODIAN"
    """Third-party custodian (Copper). Applies to IM Pooled funds.
    Subs / redemptions via the Odum portal; settlement via Copper.
    Odum never custodies directly. POD affiliate is the internal
    operating entity but MUST NOT surface in public UI strings."""

    NOT_APPLICABLE = "NOT_APPLICABLE"
    """Admin + IM-desk rows — no client-facing custody relationship.
    The BU exists purely for internal capacity reservation semantics."""


BusinessUnit = Literal["saas", "im_desk", "admin"]
"""Matches ``StrategyAvailabilityEntry.business_unit`` literal.

Kept deliberately narrow; fund-level granularity lives in
``reserving_business_unit_id`` (e.g. ``im_desk_pooled_alpha``,
``im_desk_sma_acme``, ``im_desk_reg_umbrella``)."""


ServiceFamilyTag = Literal["IM", "DART", "RegUmbrella"]
"""Prospect-facing service family the fund belongs to. Narrower than
rule 12's internal ``ServiceFamily`` — a fund never maps to the
internal-only values (``admin``, ``IM_desk``, ``DART_reporting_only``)
because a fund is a commercial product, not an internal role."""


class FundBusinessUnitEntry(BaseModel):
    """One record per (fund_id, business_unit) pair.

    ``fund_id`` is the stable external identifier (e.g. ``imp_alpha``,
    ``sma_acme_llc``, ``reg_umbrella_odum_fca``). ``fund_name`` is the
    human-readable marketing name (e.g. "Odum IM Alpha Pooled Fund").
    ``reserving_business_unit_id`` is the internal capacity-budget key
    used by the allocator; conventionally ``{bu}_{fund_short_id}``.

    ``notes`` is a free-form string for registry-authors; not surfaced
    in prospect-facing UI. Must not contain POD affiliate references
    in any row carrying ``custody_model=COPPER_CUSTODIAN``.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    fund_id: str
    fund_name: str
    business_unit: BusinessUnit
    reserving_business_unit_id: str
    custody_model: CustodyModel
    service_family: ServiceFamilyTag | None = None
    notes: str = ""


