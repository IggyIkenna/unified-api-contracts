class FundNotFoundError(LookupError):
    """Raised when ``fund_for(fund_id)`` can't resolve the fund."""


def fund_for(
    fund_id: str,
    *,
    registry: Iterable[FundBusinessUnitEntry] = FUND_BUSINESS_UNIT_REGISTRY,
) -> FundBusinessUnitEntry:
    """Look up a fund record by ID. Raises ``FundNotFoundError`` on miss.

    Fail-loud: no ``str | None`` return. Consumers that want optional
    behaviour wrap the call in ``try / except FundNotFoundError``.
    """

    for entry in registry:
        if entry.fund_id == fund_id:
            return entry
    raise FundNotFoundError(
        f"fund_id={fund_id!r} not found in FUND_BUSINESS_UNIT_REGISTRY",
    )


def funds_for_business_unit(
    business_unit: BusinessUnit,
    *,
    registry: Iterable[FundBusinessUnitEntry] = FUND_BUSINESS_UNIT_REGISTRY,
) -> tuple[FundBusinessUnitEntry, ...]:
    """All fund records bound to a given business_unit literal."""

    return tuple(entry for entry in registry if entry.business_unit == business_unit)


def reserving_business_unit_for(
    fund_id: str,
    *,
    registry: Iterable[FundBusinessUnitEntry] = FUND_BUSINESS_UNIT_REGISTRY,
) -> str:
    """Resolve a fund's canonical ``reserving_business_unit_id``.

    Shortcut for ``fund_for(fund_id).reserving_business_unit_id``.
    Allocator call-sites use this to stop concatenating strings.
    """

    return fund_for(fund_id, registry=registry).reserving_business_unit_id


def _validate_registry_invariants(
    registry: Iterable[FundBusinessUnitEntry] = FUND_BUSINESS_UNIT_REGISTRY,
) -> None:
    """Invariants enforced at import time (via the ``__init__`` call below).

    * ``fund_id`` must be unique across the registry.
    * ``reserving_business_unit_id`` must be unique (the allocator keys
      capacity budgets on it — collisions would silently merge
      reservations).
    * A row with ``custody_model=COPPER_CUSTODIAN`` must NOT mention
      the POD affiliate in ``notes`` (public-copy invariant).
    """

    seen_fund_ids: set[str] = set()
    seen_reserving_ids: set[str] = set()
    for entry in registry:
        if entry.fund_id in seen_fund_ids:
            raise ValueError(
                f"duplicate fund_id in registry: {entry.fund_id!r}",
            )
        if entry.reserving_business_unit_id in seen_reserving_ids:
            raise ValueError(
                f"duplicate reserving_business_unit_id: {entry.reserving_business_unit_id!r}",
            )
        seen_fund_ids.add(entry.fund_id)
        seen_reserving_ids.add(entry.reserving_business_unit_id)
        if entry.custody_model is CustodyModel.COPPER_CUSTODIAN and "pod" in entry.notes.lower():
            raise ValueError(
                f"COPPER_CUSTODIAN rows must not surface POD affiliate in notes: {entry.fund_id!r}",
            )


_validate_registry_invariants()


