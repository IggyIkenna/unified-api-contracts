class TestAliasHygiene:
    def test_no_duplicate_canonical_names(self) -> None:
        for spec in SCHEMA_SPEC_REGISTRY:
            names = [c.name for c in spec.columns]
            assert len(names) == len(set(names)), f"duplicate canonical column in {spec.asset_group}/{spec.data_type}"

    def test_alias_never_shadows_canonical_name(self) -> None:
        """An alias duplicating a canonical name in the same spec would be the
        cosmetic-GREEN antipattern (camelCase kept as a parallel column)."""
        for spec in SCHEMA_SPEC_REGISTRY:
            canonical = {c.name for c in spec.columns}
            for col in spec.columns:
                overlap = set(col.source_aliases) & canonical
                assert not overlap, (
                    f"{spec.asset_group}/{spec.data_type}.{col.name} aliases {overlap} shadow canonical columns"
                )

    def test_carried_includes_aliases(self) -> None:
        spec = find_schema("prediction", "trades")
        assert spec is not None
        carried = carried_column_names(spec)
        assert {"condition_id", "conditionId", "outcome_index", "outcomeIndex"} <= carried

    def test_prediction_trades_carries_market_question_metadata(self) -> None:
        """title/slug/event_slug added 2026-07-28 (operator ruling 2026-07-25,
        prediction_polymarket_legacy_dual_write_trees_metadata_loss_2026_07_24.md)
        — market-question metadata with no surviving copy elsewhere. Trader-PII
        fields (proxy_wallet/name/pseudonym/bio/profile_image) stay excluded."""
        spec = find_schema("prediction", "trades")
        assert spec is not None
        carried = carried_column_names(spec)
        assert {"title", "slug", "event_slug", "eventSlug"} <= carried
        pii_fields = {"proxy_wallet", "name", "pseudonym", "bio", "profile_image"}
        assert pii_fields.isdisjoint(carried)


class TestSourceColumnCompleteness:
    @pytest.mark.parametrize(
        ("asset_group", "data_type", "venue"),
        sorted(_SAMPLED_SOURCE_COLUMNS),
    )
    def test_no_silent_truncation(self, asset_group: str, data_type: str, venue: str) -> None:
        """Every non-meta column physically present in the sampled prod
        parquets is carried by the v9 contract (CF-18 GREEN, per cell)."""
        if not data_type:
            pytest.skip("blank legacy data_type axis — not a contract key")
        spec = find_schema(asset_group, data_type)
        assert spec is not None, f"no SchemaSpec for {asset_group}/{data_type}"
        dropped = _dropped(spec, _SAMPLED_SOURCE_COLUMNS[(asset_group, data_type, venue)])
        assert not dropped, f"RED {asset_group}/{data_type}/{venue} — dropped: {sorted(dropped)}"

    @pytest.mark.parametrize(("asset_group", "data_type", "venue"), sorted(_PREVIOUSLY_RED))
    def test_previously_red_columns_now_carried(self, asset_group: str, data_type: str, venue: str) -> None:
        """Pins the exact 2026-06-11 RED lists — the operator-ratified
        'no acked drops' decision (#2) regression guard."""
        spec = find_schema(asset_group, data_type)
        assert spec is not None
        dropped = _dropped(spec, _PREVIOUSLY_RED[(asset_group, data_type, venue)])
        assert not dropped, f"previously-RED columns dropped again: {sorted(dropped)}"
