def _dropped(spec: SchemaSpec, source_columns: set[str]) -> set[str]:
    """The audit's RED condition: non-meta source columns absent from the
    carried set (canonical names ∪ source_aliases)."""
    carried = carried_column_names(spec)
    return {c for c in source_columns if c not in _PARTITION_AND_META_COLUMNS and c not in carried}


